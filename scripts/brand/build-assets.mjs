#!/usr/bin/env node
// Logo master + tokens -> every logo file the site ships.
//
//   node scripts/brand/build-assets.mjs           write everything
//   node scripts/brand/build-assets.mjs --check   fail if a text output (TS/SVG) is stale
//
// Inputs: web_client/brand/master/syd-logo.master.svg (geometry, colour-free)
//         web_client/brand/tokens/*.tokens.json   (colours, tones)
// Outputs are declared in ASSETS below; nothing else in the repo writes them.
// Raster files (PNG/ICO) are not compared by --check: their bytes depend on the
// rasteriser build. Text outputs are, and the PNGs derive from the same SVG.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { optimize } from 'svgo';
import { encodeIco } from './lib/ico.mjs';
import { VARIANTS, composeSvg, layout, readMaster, variantBox, variantPaths } from './lib/logo.mjs';
import { ROOT, loadTokens, logoPalette, resolveValue } from './lib/tokens.mjs';
import { BACKEND_BRAND_DIR, sameText } from './build-tokens.mjs';

const WEB = path.join(ROOT, 'web_client');
const PUBLIC = path.join(WEB, 'public');
const BRAND_NAME = JSON.parse(fs.readFileSync(path.join(WEB, 'brand', 'brand.json'), 'utf8')).name;
const BACKGROUND = '{logo.background}';
const SUPERSAMPLE = 4;

/**
 * Every shipped logo file. `url` is where the site serves it from; `file` (repo-relative)
 * is for a file the site does not serve (the backend's PDF logo). `backend` names the
 * logo in the backend's manifest (BACKEND_ASSETS_FILE).
 *   kind     svg | png | ico
 *   variant  full | horizontal | mark | icon
 *   tone     token tone for the colours ('default' = the logo roles)
 *   canvas   [w, h] output size in px (png/ico: per size)
 *   fit / safeCircle / padding  how the art sits on the canvas (see composeSvg)
 *   plate    paint the logo background token behind the art
 *   darkTone svg only: switch to this tone under prefers-color-scheme: dark
 */
export const ASSETS = [
    // Browser tab: ICO for legacy/fallback, SVG (adapts to dark tabs) for the rest.
    { key: 'favicon', url: '/favicon.ico', kind: 'ico', variant: 'icon', sizes: [16, 32, 48], fit: 0.94 },
    { key: 'iconSvg', url: '/brand/icon.svg', kind: 'svg', variant: 'icon', canvas: [64, 64], fit: 0.94, darkTone: 'tab-dark' },
    // Home screens. iOS fills transparency with black, so the touch icon has a plate.
    { key: 'appleTouchIcon', url: '/brand/apple-touch-icon.png', kind: 'png', variant: 'icon', canvas: [180, 180], fit: 0.72, plate: true },
    { key: 'pwa192', url: '/brand/icon-192.png', kind: 'png', variant: 'icon', canvas: [192, 192], fit: 0.8, plate: true },
    { key: 'pwa512', url: '/brand/icon-512.png', kind: 'png', variant: 'icon', canvas: [512, 512], fit: 0.8, plate: true },
    // Android adaptive icon: the launcher may crop to a circle of 80 % (W3C safe zone);
    // 78 % keeps the anti-aliased corner of the leaf inside it too.
    { key: 'maskable512', url: '/brand/icon-maskable-512.png', kind: 'png', variant: 'icon', canvas: [512, 512], safeCircle: 0.78, plate: true },
    // Structured data (Organization/publisher logo, >= 112 px) and downloads.
    { key: 'logoSvg', url: '/brand/syd-logo.svg', kind: 'svg', variant: 'full', padding: 0.04 },
    { key: 'logoPng', url: '/brand/syd-logo.png', kind: 'png', variant: 'full', width: 1200, padding: 0.04 },
    // Default link preview (Open Graph 1.91:1).
    { key: 'ogDefault', url: '/brand/og-default.png', kind: 'png', variant: 'full', canvas: [1200, 630], fit: 0.6, plate: true },
    // Quote emails (backend): fetched by the mail client from the site, shown at 1/3 size
    // (222 x 40, the lockup's own proportions: its left edge lines up with the text).
    // The plate keeps it legible when a client darkens the message.
    { key: 'emailLogo', url: '/brand/email-logo.png', kind: 'png', variant: 'horizontal', canvas: [666, 120], fit: 1, plate: true, backend: 'email' },
    // Quote PDF (backend): drawn about 50 mm wide, so 1600 px is ~800 dpi.
    { key: 'pdfLogo', file: 'backend_python/src/brand/logo-horizontal.png', kind: 'png', variant: 'horizontal', width: 1600, backend: 'pdf' },
];

/** Logo sizes and locations for the backend (quote emails and PDF), next to its tokens JSON. */
export const BACKEND_ASSETS_FILE = path.join(BACKEND_BRAND_DIR, 'assets.generated.json');

const TS_ART = path.join(WEB, 'lib', 'brand', 'logo-art.generated.ts');
const TS_ASSETS = path.join(WEB, 'lib', 'brand', 'assets.generated.ts');
const HEADER = 'GENERATED by scripts/brand/build-assets.mjs from web_client/brand — do not edit.';

const fileFor = (url) => path.join(PUBLIC, ...url.split('/').filter(Boolean));
const assetFile = (a) => (a.file ? path.join(ROOT, a.file) : fileFor(a.url));

function svgoClean(svg, { keepStyles = false } = {}) {
    return optimize(svg, {
        multipass: true,
        plugins: [
            {
                name: 'preset-default',
                params: {
                    overrides: {
                        // A <style> with a prefers-color-scheme rule must stay a
                        // stylesheet: inlined fills would beat the media query.
                        ...(keepStyles ? { inlineStyles: false, mergeStyles: false } : {}),
                    },
                },
            },
        ],
    }).data;
}

function darkStyle(palette) {
    const rules = Object.entries(palette).map(([role, c]) => `.logo-${role}{fill:${c}}`).join('');
    return `@media (prefers-color-scheme:dark){${rules}}`;
}

function assetSvg(master, tokens, a) {
    const palette = logoPalette(tokens, a.tone ?? 'default');
    const background = a.plate ? resolveValue(tokens, BACKGROUND) : undefined;
    const common = { palette, background, padding: a.padding, fit: a.fit, safeCircle: a.safeCircle };
    if (a.darkTone) {
        const dark = logoPalette(tokens, a.darkTone);
        const used = new Set(variantPaths(master, a.variant).map((p) => p.role));
        const darkUsed = Object.fromEntries(Object.entries(dark).filter(([r]) => used.has(r)));
        return composeSvg(master, a.variant, { ...common, canvas: a.canvas, useClasses: true, extraStyle: darkStyle(darkUsed) });
    }
    if (a.kind === 'svg') return composeSvg(master, a.variant, { ...common, title: BRAND_NAME });
    return composeSvg(master, a.variant, { ...common, canvas: a.canvas });
}

/** Rasterise at SUPERSAMPLE x the target size (librsvg: density 72 = 1 px per unit), then downscale. */
async function rasterize(svg, width, height) {
    const [, , vbW, vbH] = /viewBox="([^"]+)"/.exec(svg)[1].split(/\s+/).map(Number);
    const density = 72 * SUPERSAMPLE * Math.max(width / vbW, height / vbH);
    return sharp(Buffer.from(svg), { density })
        .resize(width, height, { fit: 'fill' })
        .png({ compressionLevel: 9, effort: 10 })
        .toBuffer();
}

/** Text outputs: [file, content]. */
function renderText(master, tokens) {
    const out = [];
    for (const a of ASSETS.filter((x) => x.kind === 'svg')) {
        out.push([fileFor(a.url), svgoClean(assetSvg(master, tokens, a), { keepStyles: Boolean(a.darkTone) }) + '\n']);
    }
    // Each part is stored once; a variant lists the parts it shows, with the
    // lockup transform where it has one: ~5 KB for all variants together.
    const round = (n) => Number(n.toFixed(4));
    const art = Object.fromEntries(
        Object.keys(VARIANTS).map((v) => {
            const { box, parts } = layout(master, v);
            return [
                v,
                {
                    viewBox: box.map((n) => Number(n.toFixed(2))),
                    layers: parts.map(({ part, transform }) => (transform ? { part, transform: transform.map(round) } : { part })),
                },
            ];
        }),
    );
    const json = (v) => JSON.stringify(v, null, 4);
    out.push([
        TS_ART,
        [
            `// ${HEADER}`,
            '// Logo geometry. Paths are filled with var(--logo-<role>) (app/brand-tokens.css),',
            '// so colours and tones never live in this file.',
            '',
            "import type { LogoRole } from './tokens.generated';",
            '',
            `export const LOGO_PARTS = ${json(master.groups)} as const satisfies Record<string, readonly { role: LogoRole; d: string }[]>;`,
            'export type LogoPart = keyof typeof LOGO_PARTS;',
            '',
            'export interface LogoArt {',
            '    /** [minX, minY, width, height] */',
            '    readonly viewBox: readonly [number, number, number, number];',
            '    /** Parts drawn in order; transform = [scale, translateX, translateY]. */',
            '    readonly layers: readonly { readonly part: LogoPart; readonly transform?: readonly [number, number, number] }[];',
            '}',
            '',
            `export const LOGO_VARIANTS = ${json(Object.keys(VARIANTS))} as const;`,
            'export type LogoVariant = (typeof LOGO_VARIANTS)[number];',
            '',
            `export const LOGO_ART: Record<LogoVariant, LogoArt> = ${json(art)};`,
            '',
        ].join('\n'),
    ]);
    const assets = {};
    for (const a of ASSETS.filter((x) => x.url)) {
        const entry = { url: a.url, type: { svg: 'image/svg+xml', png: 'image/png', ico: 'image/x-icon' }[a.kind] };
        if (a.kind === 'ico') entry.sizes = a.sizes.map((s) => `${s}x${s}`).join(' ');
        if (a.kind === 'png') {
            const [w, h] = a.canvas ?? sizeFor(master, a);
            Object.assign(entry, { width: w, height: h });
        }
        if (a.safeCircle) entry.purpose = 'maskable';
        assets[a.key] = entry;
    }
    out.push([
        TS_ASSETS,
        [
            `// ${HEADER}`,
            '// Public URL, type and pixel size of every logo file (see ASSETS in the script).',
            '',
            `export const BRAND_ASSETS = ${json(assets)} as const;`,
            '',
        ].join('\n'),
    ]);
    const logos = Object.fromEntries(
        ASSETS.filter((a) => a.backend).map((a) => {
            const [width, height] = a.canvas ?? sizeFor(master, a);
            const where = a.file ? { file: path.basename(a.file) } : { url: a.url };
            return [a.backend, { ...where, width, height }];
        }),
    );
    out.push([BACKEND_ASSETS_FILE, `${JSON.stringify({ $comment: HEADER, logos }, null, 2)}\n`]);
    return out;
}

function sizeFor(master, a) {
    const [, , bw, bh] = variantBox(master, a.variant);
    const p = (a.padding ?? 0) * Math.max(bw, bh);
    return [a.width, Math.round((a.width * (bh + 2 * p)) / (bw + 2 * p))];
}

async function renderBinary(master, tokens) {
    const out = [];
    for (const a of ASSETS) {
        if (a.kind === 'png') {
            const [w, h] = a.canvas ?? sizeFor(master, a);
            out.push([assetFile(a), await rasterize(assetSvg(master, tokens, a), w, h)]);
        } else if (a.kind === 'ico') {
            const svg = assetSvg(master, tokens, { ...a, canvas: [1, 1] });
            const images = await Promise.all(a.sizes.map(async (s) => ({ size: s, png: await rasterize(svg, s, s) })));
            out.push([assetFile(a), encodeIco(images)]);
        }
    }
    return out;
}

export async function main(argv = process.argv.slice(2)) {
    const tokens = loadTokens();
    const master = readMaster();
    const text = renderText(master, tokens);
    if (argv.includes('--check')) {
        const stale = text.filter(([f, c]) => !fs.existsSync(f) || !sameText(fs.readFileSync(f, 'utf8'), c));
        for (const [f] of stale) console.error(`stale: ${path.relative(ROOT, f).replaceAll('\\', '/')} (run npm run brand:build)`);
        const missing = ASSETS.filter((a) => a.kind !== 'svg' && !fs.existsSync(assetFile(a)));
        for (const a of missing) console.error(`missing: ${a.file ?? `public${a.url}`} (run npm run brand:build)`);
        if (stale.length || missing.length) process.exit(1);
        console.log(`brand assets up to date (${text.length} text files, ${ASSETS.length} assets)`);
        return;
    }
    for (const [file, content] of [...text, ...(await renderBinary(master, tokens))]) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
        const size = typeof content === 'string' ? Buffer.byteLength(content) : content.length;
        console.log(`wrote ${path.relative(ROOT, file).replaceAll('\\', '/')} (${size} B)`);
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
