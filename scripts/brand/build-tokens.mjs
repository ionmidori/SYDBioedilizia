#!/usr/bin/env node
// Design tokens -> code. The DTCG files in web_client/brand/tokens are the only
// place colour values are written; this turns them into:
//   web_client/app/brand-tokens.css        roles, surfaces, Tailwind @theme + logo custom properties
//   web_client/lib/brand/tokens.generated.ts typed constants for TS code
//   scripts/brand/generated/roles.json      role vocabulary for the .mjs tools (codemod, guards)
//
// It is also the contrast gate: a theme that misses a role requirement fails the build.
//
//   node scripts/brand/build-tokens.mjs           write the files
//   node scripts/brand/build-tokens.mjs --check   fail if they are out of date
//
// The token files follow the W3C DTCG format, so a tool such as Style Dictionary
// can replace this formatter later without touching them. It is not used today:
// its dependency tree adds npm-audit advisories for what is ~60 lines here.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadTokens, resolveValue, toneNames } from './lib/tokens.mjs';
import { fontThemeLines, fontVariables, wordmarkUtility } from './lib/typography.mjs';
import { activeThemeName, cssColor, elevationLevels, loadRoles, loadTheme, shadowCss, themeNames, validateTheme } from './lib/semantic.mjs';

export const CSS_FILE = path.join(ROOT, 'web_client', 'app', 'brand-tokens.css');
export const TS_FILE = path.join(ROOT, 'web_client', 'lib', 'brand', 'tokens.generated.ts');
export const ROLES_FILE = path.join(ROOT, 'scripts', 'brand', 'generated', 'roles.json');

const HEADER = 'GENERATED by scripts/brand/build-tokens.mjs from web_client/brand/tokens — do not edit.';
const kebab = (parts) => parts.join('-').toLowerCase();
/** Git may check text files out with CRLF (core.autocrlf on Windows): compare content, not line endings. */
export const sameText = (a, b) => a != null && a.replaceAll('\r\n', '\n') === b.replaceAll('\r\n', '\n');

/** Depth-first list of [path, token] for every node that has a $value. */
function leaves(node, trail = []) {
    if (node && typeof node === 'object' && '$value' in node) return [[trail, node]];
    return Object.entries(node ?? {})
        .filter(([k]) => !k.startsWith('$'))
        .flatMap(([k, child]) => leaves(child, [...trail, k]));
}

const hex = (tree, token) => String(resolveValue(tree, token.$value)).toLowerCase();

export function toneClass(tone) {
    return `brand-tone-${tone}`;
}

export function surfaceClass(surface) {
    return `surface-${surface}`;
}

/** Roles and the active theme, shared by the CSS, TS and JSON outputs. */
export function semanticContext(tree) {
    const roles = loadRoles(tree);
    return { roles, theme: loadTheme(tree, activeThemeName(), roles) };
}

function renderRolesCss(tree, { roles, theme }) {
    const base = theme.surfaces.default;
    const rootVars = [
        ...(theme.colorScheme !== 'normal' ? [`  color-scheme: ${theme.colorScheme};`] : []),
        ...roles.names.map((r) => `  --role-${r}: ${cssColor(base[r])};`),
    ];
    const contextual = Object.entries(theme.surfaces).filter(([s]) => s !== 'default');
    // The variables live in a Tailwind utility, so the design system (and no-unknown-classes) knows the class.
    const surfaceUtilities = contextual.map(([s, values]) => {
        const changed = roles.names.filter((r) => cssColor(values[r]) !== cssColor(base[r]));
        const tone = theme.logoTone[s];
        const logo = tone ? leaves(tree.tone[tone]).map(([p, t]) => `  --logo-${kebab(p)}: ${hex(tree, t)};`) : [];
        return [`@utility ${surfaceClass(s)} {`, ...changed.map((r) => `  --role-${r}: ${cssColor(values[r])};`), ...logo, '}'].join('\n');
    });
    // Its own paint stays in the base layer, so bg-* / text-* utilities on the same element still win.
    const surfacePaint = contextual.map(([s]) =>
        [`  .${surfaceClass(s)} {`, '    background-color: var(--role-canvas);', '    color: var(--role-ink);', '  }'].join('\n'),
    );
    const inline = [
        // No default palette (bg-white, text-slate-400, ...): the roles and the brand
        // primitives below are the only colour utilities. First, so it precedes them all.
        '  --color-*: initial;',
        ...roles.names.map((r) => `  --color-${r}: var(--role-${r});`),
        ...elevationLevels(tree).map((l) => `  --shadow-${l}: ${shadowCss(tree.elevation[l], roles, `elevation.${l}`)};`),
        // Font roles read the next/font variable at use time (it is set on <body>, not :root).
        ...fontThemeLines(tree),
    ];
    const wordmark = wordmarkUtility(tree);
    return [
        `/* Semantic roles, theme "${theme.name}": the colour vocabulary of the UI (bg-canvas, text-ink, border-line, ...). */`,
        `:root {\n${rootVars.join('\n')}\n}`,
        '',
        '/* Contextual surfaces: a container with the class surface-<name> redefines the roles (and the logo tone)',
        '   for its subtree, and paints itself with its canvas and ink. */',
        ...surfaceUtilities,
        `@layer base {\n${surfacePaint.join('\n')}\n}`,
        '',
        '/* Utilities read the role variables at use time (inline), so a surface can override them. */',
        `@theme inline {\n${inline.join('\n')}\n}`,
        ...(wordmark ? ['', '/* The brand name inside running text, set like the logo (typography.tokens.json). */', wordmark] : []),
    ];
}

export function renderCss(tree, ctx = semanticContext(tree)) {
    const theme = leaves(tree.color, ['color']).map(([p, t]) => `  --${kebab(p)}: ${hex(tree, t)};`);
    const logo = leaves(tree.logo).map(([p, t]) => `  --logo-${kebab(p)}: ${hex(tree, t)};`);
    const tones = toneNames(tree)
        .filter((t) => t !== 'default')
        .map((tone) => {
            const vars = leaves(tree.tone[tone]).map(([p, t]) => `  --logo-${kebab(p)}: ${hex(tree, t)};`);
            return `.${toneClass(tone)} {\n${vars.join('\n')}\n}`;
        });
    return [
        `/* ${HEADER} */`,
        '',
        ...renderRolesCss(tree, ctx),
        '',
        '/* Colour utilities (bg-brand-navy-900, bg-third-party-google-blue, ...). */',
        `@theme {\n${theme.join('\n')}\n}`,
        '',
        '/* Logo roles: the logo artwork fills its shapes with these, never with a colour. */',
        `:root {\n${logo.join('\n')}\n}`,
        '',
        '/* Logo tones: override the roles for a surface (class set by <BrandLogo tone>). */',
        ...tones,
        '',
    ].join('\n');
}

function nest(tree, node) {
    if (node && typeof node === 'object' && '$value' in node) return hex(tree, node);
    const out = {};
    for (const [k, child] of Object.entries(node ?? {})) if (!k.startsWith('$')) out[k] = nest(tree, child);
    return out;
}

const constName = (s) => s.toUpperCase().replaceAll('-', '_');
const pascal = (s) => s.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

export function renderTs(tree, { roles, theme } = semanticContext(tree)) {
    const logoRoles = leaves(tree.logo).map(([p]) => kebab(p));
    const tones = toneNames(tree);
    const toneClasses = Object.fromEntries(tones.filter((t) => t !== 'default').map((t) => [t, toneClass(t)]));
    const json = (v) => JSON.stringify(v, null, 4);
    const families = Object.entries(roles.families).flatMap(([f, { members }]) => [
        `export const ${constName(f)}_TONES = ${json(members)} as const;`,
        `export type ${pascal(f)}Tone = (typeof ${constName(f)}_TONES)[number];`,
        '',
    ]);
    const resolved = Object.fromEntries(
        Object.entries(theme.surfaces).map(([s, v]) => [s, Object.fromEntries(roles.names.map((r) => [r, cssColor(v[r])]))]),
    );
    return [
        `// ${HEADER}`,
        '',
        `export const brandColors = ${json(nest(tree, tree.color))} as const;`,
        '',
        `export const logoColors = ${json(nest(tree, tree.logo))} as const;`,
        '',
        `export const LOGO_ROLES = ${json(logoRoles)} as const;`,
        'export type LogoRole = (typeof LOGO_ROLES)[number];',
        '',
        `export const LOGO_TONES = ${json(tones)} as const;`,
        'export type LogoTone = (typeof LOGO_TONES)[number];',
        '',
        '/** CSS class that applies a tone (defined in app/brand-tokens.css). */',
        `export const LOGO_TONE_CLASS: Record<Exclude<LogoTone, 'default'>, string> = ${json(toneClasses)};`,
        '',
        '/** Theme shipped by the site (web_client/brand/brand.json). */',
        `export const ACTIVE_THEME = ${JSON.stringify(theme.name)};`,
        '',
        '/** Semantic colour roles (web_client/brand/tokens/roles.tokens.json): the only colour vocabulary of the UI. */',
        `export const ROLE_NAMES = ${json(roles.names)} as const;`,
        'export type Role = (typeof ROLE_NAMES)[number];',
        '',
        '/** Roles that colour text: no opacity modifier on these, so their contrast stays checkable. */',
        `export const TEXT_ROLES = ${json(roles.textRoles)} as const;`,
        'export type TextRole = (typeof TEXT_ROLES)[number];',
        '',
        '/** Contextual surfaces; every one but `default` is applied with the class surface-<name>. */',
        `export const SURFACES = ${json(Object.keys(theme.surfaces))} as const;`,
        'export type Surface = (typeof SURFACES)[number];',
        '',
        ...families,
        '/** next/font face and CSS variable of each font role (typography.tokens.json); app/layout.tsx is held to these. */',
        `export const FONT_VARIABLES = ${json(fontVariables(tree))} as const;`,
        'export type FontRole = keyof typeof FONT_VARIABLES;',
        '',
        `export const ELEVATION_LEVELS = ${json(elevationLevels(tree))} as const;`,
        'export type ElevationLevel = (typeof ELEVATION_LEVELS)[number];',
        '',
        '/** Resolved role colours of the active theme, per surface (#rrggbb, #rrggbbaa when translucent). */',
        `export const themeRoles = ${json(resolved)} as const;`,
        '',
    ].join('\n');
}

/** Role vocabulary for the .mjs tools (codemod, colour guards), which cannot import TS. */
export function renderRolesJson(tree, { roles, theme } = semanticContext(tree)) {
    const data = {
        $comment: HEADER,
        theme: theme.name,
        roles: roles.names,
        textRoles: roles.textRoles,
        surfaces: Object.keys(theme.surfaces),
        families: Object.fromEntries(Object.entries(roles.families).map(([f, { members }]) => [f, members])),
        elevationLevels: elevationLevels(tree),
    };
    return `${JSON.stringify(data, null, 2)}\n`;
}

export function renderAll(tree = loadTokens()) {
    const ctx = semanticContext(tree);
    return [
        [CSS_FILE, renderCss(tree, ctx)],
        [TS_FILE, renderTs(tree, ctx)],
        [ROLES_FILE, renderRolesJson(tree, ctx)],
    ];
}

/** Contrast gate: one line per failed role requirement, in every theme. */
export function contrastFailures(tree = loadTokens()) {
    const roles = loadRoles(tree);
    return themeNames()
        .map((name) => loadTheme(tree, name, roles))
        .flatMap((t) =>
            validateTheme(roles, t).map(
                (f) => `${t.name}/${f.surface}: ${f.fg} on ${f.bg}${f.backdrop ? ` over ${f.backdrop}` : ''} = ${f.actual.toFixed(2)}:1, needs ${f.min}:1`,
            ),
        );
}

function main() {
    const check = process.argv.includes('--check');
    const tree = loadTokens();
    const fails = contrastFailures(tree);
    if (fails.length) {
        console.error(`contrast gate: ${fails.length} role requirement(s) failed (web_client/brand/tokens/themes)`);
        for (const f of fails) console.error(`  ${f}`);
        process.exit(1);
    }
    let stale = 0;
    for (const [file, content] of renderAll(tree)) {
        const rel = path.relative(ROOT, file).replaceAll('\\', '/');
        const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
        if (check) {
            if (!sameText(current, content)) {
                console.error(`stale: ${rel} (run npm run brand:build)`);
                stale++;
            }
            continue;
        }
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
        console.log(`wrote ${rel}`);
    }
    if (stale) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
