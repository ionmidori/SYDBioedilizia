#!/usr/bin/env node
// Design tokens -> code. The DTCG files in web_client/brand/tokens are the only
// place colour values are written; this turns them into:
//   web_client/app/brand-tokens.css        Tailwind @theme + logo custom properties
//   web_client/lib/brand/tokens.generated.ts typed constants for TS code
//
//   node scripts/brand/build-tokens.mjs           write the files
//   node scripts/brand/build-tokens.mjs --check   fail if they are out of date
//
// The token files follow the W3C DTCG format, so a tool such as Style Dictionary
// can replace this formatter later without touching them. It is not used today:
// its dependency tree adds npm-audit advisories for what is ~60 lines here.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadTokens, resolveValue, toneNames } from './lib/tokens.mjs';

export const CSS_FILE = path.join(ROOT, 'web_client', 'app', 'brand-tokens.css');
export const TS_FILE = path.join(ROOT, 'web_client', 'lib', 'brand', 'tokens.generated.ts');

const HEADER = 'GENERATED by scripts/brand/build-tokens.mjs from web_client/brand/tokens — do not edit.';
const kebab = (parts) => parts.join('-').toLowerCase();
/** Git may check text files out with CRLF (core.autocrlf on Windows): compare content, not line endings. */
export const sameText = (a, b) => a != null && a.replaceAll('\r\n', '\n') === b.replaceAll('\r\n', '\n');

/** Depth-first list of [path, token] for every node that has a $value. */
function leaves(node, trail = []) {
    if (node && typeof node === 'object' && '$value' in node) return [[trail, node]];
    return Object.entries(node ?? {})
        .filter(([k]) => !k.startsWith('$'))
        .flatMap(([k, child]) => leaves(child, [...trail, k]));
}

const hex = (tree, token) => String(resolveValue(tree, token.$value)).toLowerCase();

export function toneClass(tone) {
    return `brand-tone-${tone}`;
}

export function renderCss(tree) {
    const theme = leaves(tree.color, ['color']).map(([p, t]) => `  --${kebab(p)}: ${hex(tree, t)};`);
    const logo = leaves(tree.logo).map(([p, t]) => `  --logo-${kebab(p)}: ${hex(tree, t)};`);
    const tones = toneNames(tree)
        .filter((t) => t !== 'default')
        .map((tone) => {
            const vars = leaves(tree.tone[tone]).map(([p, t]) => `  --logo-${kebab(p)}: ${hex(tree, t)};`);
            return `.${toneClass(tone)} {\n${vars.join('\n')}\n}`;
        });
    return [
        `/* ${HEADER} */`,
        '',
        '/* Colour utilities (bg-brand-navy-900, text-luxury-gold, ...). */',
        `@theme {\n${theme.join('\n')}\n}`,
        '',
        '/* Logo roles: the logo artwork fills its shapes with these, never with a colour. */',
        `:root {\n${logo.join('\n')}\n}`,
        '',
        '/* Logo tones: override the roles for a surface (class set by <BrandLogo tone>). */',
        ...tones,
        '',
    ].join('\n');
}

function nest(tree, node) {
    if (node && typeof node === 'object' && '$value' in node) return hex(tree, node);
    const out = {};
    for (const [k, child] of Object.entries(node ?? {})) if (!k.startsWith('$')) out[k] = nest(tree, child);
    return out;
}

export function renderTs(tree) {
    const roles = leaves(tree.logo).map(([p]) => kebab(p));
    const tones = toneNames(tree);
    const toneClasses = Object.fromEntries(tones.filter((t) => t !== 'default').map((t) => [t, toneClass(t)]));
    const json = (v) => JSON.stringify(v, null, 4);
    return [
        `// ${HEADER}`,
        '',
        `export const brandColors = ${json(nest(tree, tree.color))} as const;`,
        '',
        `export const logoColors = ${json(nest(tree, tree.logo))} as const;`,
        '',
        `export const LOGO_ROLES = ${json(roles)} as const;`,
        'export type LogoRole = (typeof LOGO_ROLES)[number];',
        '',
        `export const LOGO_TONES = ${json(tones)} as const;`,
        'export type LogoTone = (typeof LOGO_TONES)[number];',
        '',
        '/** CSS class that applies a tone (defined in app/brand-tokens.css). */',
        `export const LOGO_TONE_CLASS: Record<Exclude<LogoTone, 'default'>, string> = ${json(toneClasses)};`,
        '',
    ].join('\n');
}

export function renderAll(tree = loadTokens()) {
    return [
        [CSS_FILE, renderCss(tree)],
        [TS_FILE, renderTs(tree)],
    ];
}

function main() {
    const check = process.argv.includes('--check');
    let stale = 0;
    for (const [file, content] of renderAll()) {
        const rel = path.relative(ROOT, file).replaceAll('\\', '/');
        const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
        if (check) {
            if (!sameText(current, content)) {
                console.error(`stale: ${rel} (run npm run brand:build)`);
                stale++;
            }
            continue;
        }
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
        console.log(`wrote ${rel}`);
    }
    if (stale) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
