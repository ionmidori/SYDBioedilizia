"""Generate contracts/money/golden_vectors.json — the money cases backend and frontend must agree on.

    uv run python scripts/generate_money_vectors.py

The expected values come from an oracle written here with exact fractions,
independent of `src/core/money.py` (Python) and `web_client/lib/money.ts` (TS):
both are tested against this file (`tests/unit/test_money_golden.py`,
`lib/__tests__/money.golden.test.ts`), and a test fails if the file is not what
this script produces.

The rule, as the oracle implements it:
- an input number means the decimal it prints as (shortest round-trip form:
  Python `repr`, JS `String`), so 1.005 is 1.005, not the binary value below it;
- rounding is to the cent, half away from zero (ROUND_HALF_UP);
- line = round(qty x unit_price) -> subtotal = sum of lines ->
  VAT = round(subtotal x rate) -> total = subtotal + VAT.
"""
from __future__ import annotations

import json
import random
from fractions import Fraction
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[2] / "contracts" / "money" / "golden_vectors.json"
_SEED = 20261023


def _exact(value: float) -> Fraction:
    return Fraction(repr(value))


def _cents(value: Fraction) -> int:
    """Half away from zero, to integer cents."""
    scaled = abs(value) * 100
    whole = scaled.numerator // scaled.denominator
    if scaled - whole >= Fraction(1, 2):
        whole += 1
    return -whole if value < 0 else whole


def _text(cents: int) -> str:
    sign = "-" if cents < 0 else ""
    return f"{sign}{abs(cents) // 100}.{abs(cents) % 100:02d}"


def _line(qty: float, unit_price: float) -> int:
    return _cents(_exact(qty) * _exact(unit_price))


def _vat(subtotal_cents: int, rate: float) -> int:
    return _cents(Fraction(subtotal_cents, 100) * _exact(rate))


# ── Notable cases (each one broke, or would break, a float implementation) ────

_TO_CENTS = [0.125, 2.675, 1.005, 0.004999, 0.005, -0.005, -1.005, 1e-07, 0.1 + 0.2, 1234567.895, 0, 99.999]

_LINES = [
    (0.5, 22.25),  # 11.125: Python round() gives 11.12 (half-even on an exact binary tie)
    (1, 1.005),  # 1.005 is 1.00499999... in binary: float rounding gives 1.00
    (3, 0.335),  # 1.0050000000000001 in float
    (2, 33.33),
    (10, 12.5),
    (0.1, 0.7),
    (1.15, 1),
    (2.675, 1),
    (0, 99.99),
    (0.001, 4.99),
    (0.003, 1.5),
    (0.01, 50),
    (1e-07, 1),
    (33.333, 3),
    (10000, 999999.99),
    (7, 0.145),
    (12.345, 0.1),
]

_VAT = [
    (25, 0.22),  # 0.055
    (1125, 0.1),  # 1.125
    (2275, 0.22),  # 5.005
    (5, 0.1),  # 0.005
    (19166, 0.22),
    (100000, 0.04),
    (12345, 0),
    (0, 0.22),
    (33333, 0.05),
]

_TOTALS = [
    ([(10, 12.5), (2, 33.33)], 0.22),
    ([(0.5, 22.25)], 0.22),
    ([(1, 1.005), (3, 0.335), (0.5, 22.25)], 0.1),
    ([(1, 0.1), (1, 0.2)], 0.22),
    ([], 0.22),
    ([(40, 18.5), (12.5, 27.9), (1, 350)], 0.04),
]


def _random_decimal(rng: random.Random, max_units: int, places: int) -> float:
    return float(f"{rng.randint(0, max_units * 10**places) / 10**places:.{places}f}")


def build_vectors() -> dict:
    rng = random.Random(_SEED)
    lines = list(_LINES)
    for _ in range(240):
        lines.append((_random_decimal(rng, 500, rng.choice((0, 1, 2, 3))), _random_decimal(rng, 2000, rng.choice((2, 3)))))
    vat = list(_VAT)
    for _ in range(120):
        vat.append((rng.randint(0, 10_000_000), rng.choice((0, 0.04, 0.05, 0.1, 0.22))))
    totals = list(_TOTALS)
    for _ in range(60):
        items = [
            (_random_decimal(rng, 200, rng.choice((0, 1, 2))), _random_decimal(rng, 1500, rng.choice((2, 3))))
            for _ in range(rng.randint(1, 6))
        ]
        totals.append((items, rng.choice((0, 0.04, 0.1, 0.22))))

    def totals_case(items: list[tuple[float, float]], rate: float) -> dict:
        subtotal = sum(_line(q, p) for q, p in items)
        vat_cents = _vat(subtotal, rate)
        return {
            "items": [{"qty": q, "unit_price": p} for q, p in items],
            "vat_rate": rate,
            "expected": {
                "lines": [_text(_line(q, p)) for q, p in items],
                "subtotal": _text(subtotal),
                "vat_amount": _text(vat_cents),
                "grand_total": _text(subtotal + vat_cents),
            },
        }

    return {
        "description": (
            "Generated by backend_python/scripts/generate_money_vectors.py — do not edit by hand. "
            "Inputs are JSON numbers (read as their shortest decimal form); expected amounts are "
            "strings with exactly two decimals, rounded half away from zero."
        ),
        "to_cents": [{"value": v, "expected": _text(_cents(_exact(v)))} for v in _TO_CENTS],
        "line_total": [{"qty": q, "unit_price": p, "expected": _text(_line(q, p))} for q, p in lines],
        "vat_amount": [
            {"subtotal": float(_text(s)), "vat_rate": r, "expected": _text(_vat(s, r))} for s, r in vat
        ],
        "compute_totals": [totals_case(items, rate) for items, rate in totals],
    }


def render() -> str:
    return json.dumps(build_vectors(), indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")
