"""Reset the guest render quota: DELETES a live Firestore document.

Removes `usage_quotas/guest-session-_generate_render`, the shared counter of
renders generated by anonymous guests, so guests can render again.

It writes to whatever project the credentials in `.env` point at (including
production). Without `--yes` it only prints what it would delete.

Usage (from backend_python/):
    uv run python scripts/reset_guest_render_quota.py          # dry run
    uv run python scripts/reset_guest_render_quota.py --yes    # delete
"""
import argparse
import sys
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

# Make `src` importable from any cwd: this file lives in backend_python/scripts/.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.db.firebase_client import get_firestore_client  # noqa: E402

COLLECTION = "usage_quotas"
DOCUMENT = "guest-session-_generate_render"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--yes", action="store_true", help="actually delete the document")
    args = parser.parse_args()

    doc_ref = get_firestore_client().collection(COLLECTION).document(DOCUMENT)
    snapshot = doc_ref.get()
    if not snapshot.exists:
        print(f"Nothing to do: {COLLECTION}/{DOCUMENT} does not exist.")
        return 0

    print(f"{COLLECTION}/{DOCUMENT} = {snapshot.to_dict()}")
    if not args.yes:
        print("Dry run. Re-run with --yes to delete it.")
        return 0

    doc_ref.delete()
    print(f"DELETED {COLLECTION}/{DOCUMENT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
